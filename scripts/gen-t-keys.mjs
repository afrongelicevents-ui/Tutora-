// Builds src/lib/t-keys.gen.ts: the messages that t() may look up by name at runtime
// (error codes from the server, moods, statuses...). Only these are sent to the browser,
// instead of every message (low data). Run: pnpm i18n:t  (a test checks it is up to date).
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const PREFIXES = [
	'ci_',
	'done_',
	'pdone_',
	'pg3_src_',
	'sdone_',
	'sp3_role_',
	'sp3_status_',
	'st5_day_',
	'st5_done_',
	'st5_state_',
	'err_',
	'badge_',
	'bp_',
	'cr_',
	'cs_',
	'cf_',
	'ck_ins_',
	'ds_line_',
	'ps_k_',
	'pr_ins_',
	'pr_day_'
];

export function wantedKeys(root = '.') {
	const messages = Object.keys(
		JSON.parse(readFileSync(join(root, 'messages/en.json'), 'utf8'))
	).filter((k) => k !== '$schema');
	const all = new Set(messages);
	const used = new Set();
	const walk = (dir) => {
		for (const f of readdirSync(dir)) {
			const p = join(dir, f);
			if (p.includes('paraglide')) continue;
			if (statSync(p).isDirectory()) walk(p);
			else if (/\.(ts|svelte|js)$/.test(f) && !f.endsWith('.gen.ts') && !/\.test\.ts$/.test(f)) {
				for (const mm of readFileSync(p, 'utf8').matchAll(/['"`]([a-z][a-z0-9_]*)['"`]/g))
					if (all.has(mm[1])) used.add(mm[1]);
			}
		}
	};
	walk(join(root, 'src'));
	for (const k of messages) if (PREFIXES.some((p) => k.startsWith(p))) used.add(k);
	return [...used].sort();
}

export function render(keys) {
	return (
		'// Generated by scripts/gen-t-keys.mjs. Do not edit.\n' +
		`import {\n${keys.map((k) => `\t${k}`).join(',\n')}\n} from './paraglide/messages.js';\n\n` +
		`export const T_MESSAGES = {\n${keys.map((k) => `\t${k}`).join(',\n')}\n};\n`
	);
}

if (import.meta.url === `file://${process.argv[1]}`) {
	const keys = wantedKeys();
	writeFileSync('src/lib/t-keys.gen.ts', render(keys));
	console.log(`${keys.length} messages for t()`);
}
